export function normalizePath(pathname) {
  let path = decodeURIComponent(pathname || "/").replace(/\/+$/, "") || "/";
  if (path === "/fa") return "/";
  if (path.startsWith("/fa/")) path = path.slice(3) || "/";
  return path;
}

